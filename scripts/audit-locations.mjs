// Location-page quality audit (Phase 8) — REPORT ONLY. Does not change, delete,
// redirect or noindex any page. Reads the built dist/ location pages, measures
// word count, cross-page text duplication, unique headings, indexability,
// canonical, sitemap inclusion and internal-link count, then writes a review
// table to LOCATION_AUDIT.md for owner review.
//
// No Search Console data is available in the repo, so nothing is auto-actioned:
// high-duplication indexed pages are FLAGGED for review, not removed. The sitemap
// already gates thin pages (tier > 2 city pages are noindex + excluded); this
// report tells the owner which indexed pages still lack genuinely city-specific
// value.
import { readFileSync, existsSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist');
const ORIGIN = 'https://www.apextradeshow.com';

// Which URL prefixes are "location" pages.
const isLocationPath = (p) =>
  p.startsWith('/locations/') ||
  /^\/(trade-show-canopies|trade-show-displays|banner-stands)\/[^/]+$/.test(p);

// Enumerate prerendered pages under dist by walking index.html files.
const pages = [];
const walk = (dir, base = '') => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, `${base}/${name}`);
    else if (name === 'index.html') pages.push({ path: base || '/', file: full });
  }
};
walk(DIST);

const locPages = pages.filter((p) => isLocationPath(p.path));

// Which paths are in a sitemap.
const inSitemap = new Set();
for (const sm of ['pages', 'categories', 'products', 'blog', 'locations']) {
  const f = join(DIST, `sitemap-${sm}.xml`);
  if (!existsSync(f)) continue;
  for (const m of readFileSync(f, 'utf8').matchAll(/<loc>([^<]+)<\/loc>/g)) inSitemap.add(m[1].replace(ORIGIN, '') || '/');
}

const bodyText = (html) => {
  const b = (html.match(/<div id="seo-prerender">([\s\S]*?)<\/div>\s*<\/div>/) || [])[1] || '';
  return b.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;/g, ' ').replace(/\s+/g, ' ').trim();
};
const words = (t) => t.toLowerCase().match(/[a-z0-9]+/g) || [];
const shingles = (ws, n = 6) => {
  const out = new Set();
  for (let i = 0; i + n <= ws.length; i++) out.add(ws.slice(i, i + n).join(' '));
  return out;
};
const headings = (html) => (html.match(/<h[23][^>]*>([\s\S]*?)<\/h[23]>/g) || []).map((h) => h.replace(/<[^>]+>/g, '').trim());

// Pass 1: gather text + global shingle frequency.
const recs = [];
const shingleFreq = new Map();
const headingFreq = new Map();
for (const { path, file } of locPages) {
  const html = readFileSync(file, 'utf8');
  const text = bodyText(html);
  const ws = words(text);
  const sh = shingles(ws);
  for (const s of sh) shingleFreq.set(s, (shingleFreq.get(s) || 0) + 1);
  const hs = headings(html);
  for (const h of hs) headingFreq.set(h, (headingFreq.get(h) || 0) + 1);
  recs.push({
    path,
    words: ws.length,
    sh,
    hs,
    noindex: /<meta name="robots"[^>]*noindex/i.test(html),
    canonical: (html.match(/<link rel="canonical" href="([^"]*)"/) || [])[1] || '',
    inSitemap: inSitemap.has(path),
    links: (html.match(/href="\/[^"#]*"/g) || []).length
  });
}

// Pass 2: per-page duplication% (share of shingles that also appear elsewhere)
// and count of headings unique to this page.
for (const r of recs) {
  const total = r.sh.size || 1;
  let shared = 0;
  for (const s of r.sh) if ((shingleFreq.get(s) || 0) > 1) shared++;
  r.dupPct = Math.round((shared / total) * 100);
  r.uniqueHeadings = r.hs.filter((h) => (headingFreq.get(h) || 0) === 1).length;
  // Classification (advisory only).
  if (r.noindex) r.flag = 'noindex (already gated)';
  else if (r.dupPct >= 85 && r.uniqueHeadings === 0) r.flag = 'REVIEW: indexed, highly templated, no unique headings';
  else if (r.dupPct >= 85) r.flag = 'REVIEW: indexed, highly templated';
  else r.flag = 'keep: has distinct content';
}

const indexed = recs.filter((r) => !r.noindex);
const flagged = indexed.filter((r) => r.flag.startsWith('REVIEW'));
recs.sort((a, b) => Number(b.noindex) - Number(a.noindex) || b.dupPct - a.dupPct);

const row = (r) => `| ${r.path} | ${r.words} | ${r.dupPct}% | ${r.uniqueHeadings} | ${r.noindex ? 'noindex' : 'index'} | ${r.inSitemap ? 'yes' : 'no'} | ${r.links} | ${r.flag} |`;

const md = `# Location-page quality audit

_Generated by \`npm run audit:locations\` from the built \`dist/\`. Report only — no
page was changed, redirected or noindexed. No Google Search Console export exists
in the repo, so no page is auto-actioned; high-duplication indexed pages are
FLAGGED for owner review._

## Summary

- Location pages total: **${recs.length}**
- Indexable: **${indexed.length}**  ·  noindex (already gated): **${recs.length - indexed.length}**
- In a sitemap: **${recs.filter((r) => r.inSitemap).length}**
- Flagged for review (indexed + highly templated): **${flagged.length}**
- Duplication% = share of 6-word shingles that also appear on another location page.

## How the sitemap already gates thin pages

Tier 3 city pages render \`noindex, follow\` and are excluded from the sitemap in
\`scripts/prerender.mjs\`; only Tier 1/2 cities are indexed. This report identifies
which of the **indexed** pages still read as templated so the owner can either add
genuinely city-specific value (real venues, freight notes, local projects — never
invented) or downgrade them to noindex.

## Flagged for review (${flagged.length})

| Path | Words | Dup% | Unique H | Index | Sitemap | Links | Flag |
|---|---|---|---|---|---|---|---|
${flagged.map(row).join('\n') || '| — | | | | | | | none |'}

## All location pages (worst duplication first)

| Path | Words | Dup% | Unique H | Index | Sitemap | Links | Flag |
|---|---|---|---|---|---|---|---|
${recs.map(row).join('\n')}
`;

writeFileSync(join(ROOT, 'LOCATION_AUDIT.md'), md);
console.log(`Location audit → LOCATION_AUDIT.md`);
console.log(`  ${recs.length} location pages · ${indexed.length} indexed · ${flagged.length} flagged for review · ${recs.length - indexed.length} already noindex.`);
