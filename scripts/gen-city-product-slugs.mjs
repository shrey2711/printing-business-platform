// Writes src/generated/cityProductSlugs.js: just the slugs of the city product
// pages. App.jsx needs them to declare routes, and importing them from
// src/data/cityProductPages.js pulled ~200 KB of page copy into the entry
// bundle that every visitor downloads. The page data stays in the lazy
// CityProductPage chunk.
//
//   node scripts/gen-city-product-slugs.mjs          regenerate
//   node scripts/gen-city-product-slugs.mjs --check  fail if it is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CITY_PRODUCT_PAGES } from '../src/data/cityProductPages.js';

const OUT = fileURLToPath(new URL('../src/generated/cityProductSlugs.js', import.meta.url));
const slugs = CITY_PRODUCT_PAGES.map((p) => p.slug);
const content =
  '// AUTO-GENERATED by scripts/gen-city-product-slugs.mjs from src/data/cityProductPages.js. Do not edit.\n' +
  `export const CITY_PRODUCT_SLUGS = ${JSON.stringify(slugs)};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== content) {
    console.error('src/generated/cityProductSlugs.js is stale. Run: node scripts/gen-city-product-slugs.mjs');
    process.exit(1);
  }
  console.log(`cityProductSlugs: ${slugs.length} slugs, up to date`);
} else {
  writeFileSync(OUT, content);
  console.log(`cityProductSlugs: wrote ${slugs.length} slugs`);
}
