// Generates docs/CITY_KEYWORD_MAP.md — the per-city keyword universe mapped to
// the canonical page that targets each cluster (prevents cannibalization).
// Regenerate after adding cities: `node scripts/gen-keyword-map.mjs`.

import { writeFileSync } from 'fs';
import { SEO_CITIES } from '../src/data/citySeo.js';

// cluster label -> { url slug, keyword templates (use {C} = city name) }
const CLUSTERS = [
  { name: 'Trade Show Displays (hub)', slug: 'trade-show-displays', primary: 'Trade Show Displays {C}',
    kw: ['Trade Show Booth Displays {C}', 'Custom Trade Show Displays {C}', 'Exhibition Displays {C}', 'Trade Show Booth {C}', 'Event Displays {C}'] },
  { name: 'Canopies', slug: 'trade-show-canopies', primary: null,
    kw: ['Custom Canopy Tent {C}', 'Custom Canopy {C}'] },
  { name: 'Backdrops', slug: 'trade-show-backdrops', primary: null,
    kw: ['Backdrop Printing {C}', 'Trade Show Backdrops {C}', 'Step and Repeat Backdrop {C}'] },
  { name: 'Banner Stands', slug: 'banner-stands', primary: null,
    kw: ['Banner Stands {C}', 'Retractable Banner Stands {C}'] },
  { name: 'Table Covers', slug: 'table-covers', primary: null,
    kw: ['Trade Show Table Covers {C}', 'Custom Table Covers {C}'] }
];

const lines = [];
lines.push('# Apex City Keyword Map');
lines.push('');
lines.push('_Auto-generated by `scripts/gen-keyword-map.mjs` from `SEO_CITIES`._');
lines.push('');
lines.push('Per city, the **keyword universe** (§5) is mapped to the canonical page that');
lines.push('targets each cluster. This is a semantic cluster, **not** a stuffing list (§2):');
lines.push('the page ranks for these via natural, unique local content — never by repeating');
lines.push('exact match. Each cluster lives on its own URL so the terms never cannibalize.');
lines.push('');
lines.push('**Cluster → page (all cities):**');
lines.push('');
lines.push('| Cluster | Canonical page | Indexed |');
lines.push('|---|---|---|');
for (const c of CLUSTERS) lines.push(`| ${c.name} | \`/${c.slug}/{city}\` | tier 1–2 only |`);
lines.push('');
lines.push('---');
lines.push('');

for (const city of SEO_CITIES) {
  const C = city.city;
  const idx = city.tier <= 2 ? 'indexed' : 'noindex (tier 3)';
  lines.push(`## ${C}, ${city.abbr}  ·  ${idx}`);
  lines.push('');
  lines.push(`**Primary:** \`Trade Show Displays ${C}\` → \`/trade-show-displays/${city.slug}\``);
  lines.push('');
  lines.push('| Secondary keyword | Target page |');
  lines.push('|---|---|');
  for (const cl of CLUSTERS) {
    for (const t of cl.kw) {
      lines.push(`| ${t.replace('{C}', C)} | \`/${cl.slug}/${city.slug}\` |`);
    }
  }
  lines.push('');
}

writeFileSync('docs/CITY_KEYWORD_MAP.md', lines.join('\n') + '\n');
console.log(`Wrote docs/CITY_KEYWORD_MAP.md — ${SEO_CITIES.length} cities × ${CLUSTERS.reduce((n, c) => n + c.kw.length, 0) + 1} keywords each.`);
