// Generates docs/CITY_AUDIT.md — the §29 audit table of every existing city
// page (URL, H1, title, content quality, recommended action) read from dist/.
// Run after build: `node scripts/gen-city-audit.mjs`.

import { readFileSync, existsSync, writeFileSync } from 'fs';
import { SEO_CITIES } from '../src/data/citySeo.js';

const DIST = 'dist';
const one = (h, re) => (h.match(re) || [])[1] || '';
const words = (h) => {
  const m = h.match(/id="seo-prerender">([\s\S]*?)<nav aria-label="Primary"/);
  return ((m ? m[1] : '').replace(/<[^>]+>/g, ' ').match(/[A-Za-z0-9']+/g) || []).length;
};

const rows = [];
for (const c of SEO_CITIES) {
  const f = `${DIST}/trade-show-displays/${c.slug}/index.html`;
  if (!existsSync(f)) { rows.push([c.city, '(missing)', '', '', '', '']); continue; }
  const h = readFileSync(f, 'utf8');
  const h1 = one(h, /<h1[^>]*>([^<]*)<\/h1>/).replace(/&amp;/g, '&');
  const title = one(h, /<title>([^<]*)<\/title>/).replace(/&amp;/g, '&');
  const wc = words(h);
  const indexed = c.tier <= 2;
  const quality = `${wc} words · ${indexed ? 'indexed' : 'noindex (tier 3)'}`;
  const action = indexed ? 'Keep / index (unique local content)' : 'Noindex temporarily → improve to earn indexing';
  rows.push([`${c.city}, ${c.abbr}`, `/trade-show-displays/${c.slug}`, h1, title, quality, action]);
}

const out = [
  '# City Page Audit (§29)',
  '',
  '_Auto-generated by `scripts/gen-city-audit.mjs` from the built pages._',
  '',
  'Canonical city URLs are `/{category}/{city}` (displays shown here; each city',
  'also has `/trade-show-canopies`, `/trade-show-backdrops`, `/banner-stands`,',
  '`/table-covers` variants). Old `/locations/{state}/{city}` 301-redirects in.',
  'Inter-city content uniqueness ≈ **81%** (measured, §19). No page overwritten',
  'blindly — existing content preserved and improved.',
  '',
  '| City | Existing URL | Current H1 | Current Title | Content Quality | Recommended Action |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.map((cell) => String(cell).replace(/\|/g, '\\|')).join(' | ')} |`),
  ''
].join('\n');

writeFileSync('docs/CITY_AUDIT.md', out);
console.log(`Wrote docs/CITY_AUDIT.md — ${rows.length} cities.`);
